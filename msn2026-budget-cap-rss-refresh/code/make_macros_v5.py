"""Camera-ready (minimal-change) macros: the submitted paper's macro names, recomputed
from the unified v4 results, plus the compact tables used in the camera-ready paper."""
import json
from pathlib import Path
import numpy as np
C = Path(__file__).resolve().parent
P = C.parent / 'outputs'; P.mkdir(parents=True, exist_ok=True)
J = lambda f: json.loads((C / f).read_text())
f3 = lambda x: f'{x:.3f}'; f4 = lambda x: f'{x:.4f}'; pct = lambda x: f'{x:.1f}'
main = J('results_main_grid_v4_exact.json'); S = main['summary']; rows = main['rows']
fin = J('results_main_grid_v4_finite.json')['summary']
cv = J('results_cv_holdout_v4.json')
N = 8192
M = {}
M['NumConditions'] = str(len(rows)); M['MainTrials'] = '20'
gm = lambda s, k: s[k]['grid_mean']
M['QMean'] = f4(gm(S, 'q99'))
M['AggregateGain'] = pct(100 * (gm(S, 'BOLT') / gm(S, 'q99') - 1))
h = S['h2h']['BOLT|q99']; M['PairWins'] = str(h['wins']); M['PairLosses'] = str(h['losses']); M['PairCells'] = str(h['wins'] + h['losses'] + h['ties'])
best = next(r for r in rows if r['rho_ab'] == 0.9975 and r['rho_ae'] == 0.1)
M['BestRab'] = '0.9975'; M['BestRae'] = '0.10'
M['BestDelivered'] = f"{best['policies']['BOLT']['mean_rate'] * N:,.0f}".replace(',', '{,}')
M['BestPointGain'] = pct(100 * (best['policies']['BOLT']['mean_rate'] / best['policies']['q99']['mean_rate'] - 1))
hr = S['high_reciprocity_sums']
for k, nm in (('HighSumBOLT', 'BOLT'), ('HighSumQFive', 'q95'), ('HighSumQNineNine', 'q99'), ('HighSumBOLTHtwo', 'BOLT(H=2)'),
              ('HighSumQFiveHtwo', 'q95(H=2)'), ('HighSumQNineNineHtwo', 'q99(H=2)'), ('HighSumLCB', 'BOLT-LCB')):
    M[k] = f3(hr[nm])
M['QFiveOverQNineNine'] = pct(100 * (hr['q95'] / hr['q99'] - 1)); M['BOLTOverQFive'] = pct(100 * (hr['BOLT'] / hr['q95'] - 1))
# finite-scale grid (Table)
M['FinBOLTMean'] = f4(gm(fin, 'BOLT')); M['FinQMean'] = f4(gm(fin, 'q99'))
M['FinGain'] = pct(100 * (gm(fin, 'BOLT') / gm(fin, 'q99') - 1)); M['FinBOLTBest'] = f3(fin['BOLT']['best'])
M['FinLCBMean'] = f4(gm(fin, 'BOLT-LCB'))
M['ExactLCBMean'] = f4(gm(S, 'BOLT-LCB'))
# transfer
sh = cv['shift']['H2_low_to_high']['0.2']; M['LowHighBOLT'] = f3(sh['BOLT']); M['LowHighLCB'] = f3(sh['BOLT-LCB'])
with open(P / 'bolt_macros_v5.tex', 'w') as fh:
    fh.write('% Auto-generated by code/make_macros_v5.py. Do not hand-edit.\n')
    fh.write('\n'.join(f'\\newcommand{{\\{k}}}{{{v}}}' for k, v in M.items()) + '\n')

# compact main table (policies on identical sessions)
def wl(nm):
    if nm.startswith('q99') or nm.startswith('oracle'): return '--'
    base = 'q99(H=2)' if nm.endswith('(H=2)') else 'q99'
    w = l = 0
    for r in rows:
        if r['policies']['oracle']['mean_rate'] <= 0: continue
        x = r['policies'][nm]['mean_rate']; y = r['policies'][base]['mean_rate']
        w += x > y + 1e-12; l += y > x + 1e-12
    return f'{w}/{l}'
def acc(nm):
    a = [s['acc'] for r in rows if r['rho_ab'] >= .995 for s in r['policies'][nm].get('sessions', []) if s['cap'] > 0]
    return f"{100 * np.mean(a):.0f}\\%" if a else '--'
L = ['\\begin{tabular}{lccccc}', '\\toprule', 'Policy & grid mean & feas.\\ mean & best & acc. & W/L\\\\', '\\midrule']
for nm in (('BOLT', 'BOLT'), ('BOLT-LCB', 'BOLT-LCB'), ('q95', 'q95'), ('q99', 'q99'), None,
                ('BOLT(H=2)', 'BOLT ($H{=}2$)'), ('BOLT-LCB(H=2)', 'BOLT-LCB ($H{=}2$)'), ('q95(H=2)', 'q95 ($H{=}2$)'), ('q99(H=2)', 'q99 ($H{=}2$)'),
                ('fixedcap(H=2)', 'fixed cap ($H{=}2$)'), None, ('oracle', 'oracle (hindsight)')):
    if nm is None: L.append('\\midrule'); continue
    nm_, lab_ = nm
    s = S[nm_]
    L.append(f"{lab_} & {f4(s['grid_mean'])} & {f4(s['feasible_mean'] if 'feasible_mean' in s else s.get('feas_mean', 0))} & {f3(s['best'])} & {acc(nm_) if nm_ != 'oracle' else '--'} & {wl(nm_)}\\\\")
L += ['\\bottomrule', '\\end{tabular}']
(P / 'tab_main_v5.tex').write_text('\n'.join(L) + '\n')
print(M); print(S['BOLT'].keys())
# compact ablation table for the 8-page camera-ready (one row fewer per panel)
ab = (P / 'tab_ablation_v4.tex').read_text().splitlines()
ab = [l for l in ab if not l.startswith('$\\alpha=0.01$') and not l.startswith('pilot conf.\\ 99.9')]
(P / 'tab_ablation_v5.tex').write_text('\n'.join(ab) + '\n')
